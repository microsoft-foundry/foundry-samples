[CmdletBinding()]
param([Parameter(Mandatory)][string]$SdkRoot, [Parameter(Mandatory)][string]$Output)
$ErrorActionPreference = "Stop"
$snippets = Join-Path $SdkRoot "sdk\agentserver\Azure.AI.AgentServer.A2A\tests\Snippets"
function Read-Region([string]$File, [string]$Region) {
    $text = Get-Content -LiteralPath (Join-Path $snippets $File) -Raw
    $pattern = '(?ms)^[ \t]*#region (?:Snippet:)?' + [regex]::Escape($Region) + '\r?\n(.*?)^[ \t]*#endregion'
    $match = [regex]::Match($text, $pattern)
    if (-not $match.Success) { throw "Required sample region '$Region' is missing from '$File'." }
    return $match.Groups[1].Value
}
